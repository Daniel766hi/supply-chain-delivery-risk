"""Builds the browser version of the twin.

    python web/build.py

1. web/calibration.js  - calibration data from simulation/inputs/*.csv (same
                         source as the Python model)
2. web/index.html      - one self-contained file (page + engine + data
                         inlined): open it by double-click
3. docs/index.html     - the same file, so GitHub Pages (main branch, /docs
                         folder) serves it as the project's public page
"""

import json
import sys
from pathlib import Path

WEB = Path(__file__).resolve().parent
sys.path.insert(0, str(WEB.parent / "simulation"))
from twin import load_calibration  # noqa: E402


def write_calibration():
    cal = load_calibration()
    data = {
        "modes": list(cal.modes),
        "modeMix": [round(float(x), 6) for x in cal.mode_mix],
        "currentPromise": {m: int(d) for m, d in cal.current_promise.items()},
        "leadDays": {m: [int(x) for x in cal.lead_days[m]] for m in cal.modes},
        "leadCdf": {m: [round(float(x), 6) for x in cal.lead_cdf[m]] for m in cal.modes},
        "dailyDemand": [int(x) for x in cal.daily_demand],
        "observedPeak": int(cal.observed_peak),
        "calibrationOrders": int(cal.daily_demand.sum()),
        "calibrationPeriod": "Oct 2016 - Sep 2017",
    }
    js = ("/* Generated by web/build.py from simulation/inputs/*.csv - do not edit. */\n"
          "(function (root) {\n"
          f"  var CAL = {json.dumps(data, separators=(',', ':'))};\n"
          "  if (typeof module === 'object' && module.exports) module.exports = CAL;\n"
          "  else root.TWIN_CALIBRATION = CAL;\n"
          "})(typeof self !== 'undefined' ? self : this);\n")
    (WEB / "calibration.js").write_text(js, encoding="utf-8")


def write_standalone():
    page = (WEB / "app.html").read_text(encoding="utf-8")
    for name in ("calibration.js", "twin.js", "yard.js"):
        tag = f'<script src="{name}"></script>'
        assert tag in page, f"{tag} missing from app.html"
        page = page.replace(tag, "<script>\n" + (WEB / name).read_text(encoding="utf-8") + "\n</script>")
    doc = ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
           '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
           "</head>\n<body>\n" + page + "\n</body>\n</html>\n")
    (WEB / "index.html").write_text(doc, encoding="utf-8")
    (WEB.parent / "docs" / "index.html").write_text(doc, encoding="utf-8")


if __name__ == "__main__":
    write_calibration()
    if (WEB / "app.html").exists():
        write_standalone()
    print("Built web/calibration.js" + (", web/index.html and docs/index.html" if (WEB / "app.html").exists() else ""))
